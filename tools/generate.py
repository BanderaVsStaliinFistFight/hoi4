SIZES = {'': (82, 52), 'medium': (41, 26), 'small': (10, 7)}
SS = 8  # supersampling factor for the master drawing


def star_points(cx, cy, r, rotation=-90):
    pts = []
    for i in range(10):
        rad = r if i % 2 == 0 else r * 0.382
        a = math.radians(rotation + i * 36)
        pts.append((cx + rad * math.cos(a), cy + rad * math.sin(a)))
    return pts


def draw_flag(spec, socialist=False):
    from PIL import Image, ImageDraw
    W, H = 82 * SS, 52 * SS
    img = Image.new('RGBA', (W, H), (0, 0, 0, 255))
    d = ImageDraw.Draw(img)
    k = spec['kind']

    def hstripes(colors):
        n = len(colors)
        for i, c in enumerate(colors):
            d.rectangle([0, round(i * H / n), W, round((i + 1) * H / n)], fill=c)

    def vstripes(colors):
        n = len(colors)
        for i, c in enumerate(colors):
            d.rectangle([round(i * W / n), 0, round((i + 1) * W / n), H], fill=c)

    def disc(c, r=H * 0.22, cx=W / 2, cy=H / 2):
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c)

    def star(c, r=H * 0.26, cx=W / 2, cy=H / 2):
        d.polygon(star_points(cx, cy, r), fill=c)

    def crescent(c, bg, cx=W / 2, cy=H / 2, r=H * 0.27):
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c)
        o = r * 0.32
        d.ellipse([cx - r + o, cy - r * 0.92, cx + r * 0.92 + o, cy + r * 0.92], fill=bg)

    if k == 'hstripes':
        hstripes(spec['colors'])
    elif k == 'hstripes_disc':
        hstripes(spec['colors'])
        disc(spec['disc'])
    elif k == 'vstripes_disc':
        vstripes(spec['colors'])
        disc(spec['disc'])
    elif k == 'nordic_cross':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        t = H * 0.2
        x = W * 0.36
        d.rectangle([x - t / 2, 0, x + t / 2, H], fill=spec['cross'])
        d.rectangle([0, H / 2 - t / 2, W, H / 2 + t / 2], fill=spec['cross'])
    elif k == 'greek_cross':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        t, a = H * 0.18, H * 0.36
        d.rectangle([W / 2 - t / 2, H / 2 - a, W / 2 + t / 2, H / 2 + a], fill=spec['cross'])
        d.rectangle([W / 2 - a, H / 2 - t / 2, W / 2 + a, H / 2 + t / 2], fill=spec['cross'])
    elif k == 'saltire':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        w = round(H * 0.16)
        d.line([0, 0, W, H], fill=spec['cross'], width=w)
        d.line([0, H, W, 0], fill=spec['cross'], width=w)
    elif k == 'per_pale_disc':
        vstripes([spec['left'], spec['right']])
        disc(spec['disc'])
    elif k == 'per_pale_crescent':
        vstripes([spec['left'], spec['right']])
        crescent(spec['crescent'], spec['right'], cx=W * 0.75)
    elif k == 'bordure_disc':
        d.rectangle([0, 0, W, H], fill=spec['border'])
        b = H * 0.1
        d.rectangle([b, b, W - b, H - b], fill=spec['field'])
        disc(spec['disc'])
    elif k == 'arab_revolt':
        hstripes(spec['colors'])
        d.polygon([(0, 0), (W * 0.4, H / 2), (0, H)], fill=spec['hoist'])
    elif k == 'crescent':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        crescent(spec['crescent'], spec['field'])
    elif k == 'disc':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        disc(spec['disc'], r=H * 0.27)
    elif k == 'hband_star':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        d.rectangle([0, H / 3, W, 2 * H / 3], fill=spec['band'])
        star(spec['star'], r=H * 0.2)
    elif k == 'fly_stripe':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        d.rectangle([W * 0.72, 0, W * 0.86, H], fill=spec['stripe'])
    elif k == 'star':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        star(spec['star'], r=H * 0.32)
    elif k == 'southern_cross':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        for cx, cy, r in [(0.5, 0.18, 0.09), (0.5, 0.82, 0.09), (0.36, 0.48, 0.08), (0.64, 0.42, 0.08), (0.57, 0.6, 0.05)]:
            star(spec['star'], r=H * r, cx=W * cx, cy=H * cy)
    elif k == 'hband_stars':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        d.rectangle([0, H * 0.4, W, H * 0.6], fill=spec['band'])
        for cx in (0.3, 0.5, 0.7):
            star(spec['star'], r=H * 0.09, cx=W * cx, cy=H * 0.2)
    elif k == 'ring':
        d.rectangle([0, 0, W, H], fill=spec['field'])
        r = H * 0.32
        d.ellipse([W / 2 - r, H / 2 - r, W / 2 + r, H / 2 + r], outline=spec['ring'], width=round(H * 0.06))
        star(spec['ring'], r=H * 0.12)
    else:
        raise ValueError('unknown flag kind ' + k)

    if socialist:
        cx, cy, r = W * 0.15, H * 0.24, H * 0.16
        d.polygon(star_points(cx, cy, r * 1.25), fill='#F2C200')
        d.polygon(star_points(cx, cy, r), fill='#CC0000')
    return img


def gen_flags(F):
    from PIL import Image
    flag_root = os.path.join(MOD, 'gfx', 'flags')
    if os.path.isdir(flag_root):
        shutil.rmtree(flag_root)
    masters = []
    for f in F:
        variants = [('', False)] + [('_' + i, True) for i in SOCIALIST]
        base = draw_flag(f['flag'])
        red = draw_flag(f['flag'], socialist=True)
        masters.append(base)
        for suffix, socialist in variants:
            master = red if socialist else base
            for folder, size in SIZES.items():
                out_dir = os.path.join(flag_root, folder)
                os.makedirs(out_dir, exist_ok=True)
                img = master.resize(size, Image.LANCZOS)
                img.save(os.path.join(out_dir, f'{PREFIX}_{f["id"]}{suffix}.tga'), format='TGA')
    return masters


def gen_thumbnail(masters):
    from PIL import Image
    cols, fw, fh, gap = 6, 76, 48, 8
    rows = math.ceil(len(masters) / cols)
    size = 512
    img = Image.new('RGB', (size, size), (24, 22, 20))
    grid_w = cols * fw + (cols - 1) * gap
    grid_h = rows * fh + (rows - 1) * gap
    x0, y0 = (size - grid_w) // 2, (size - grid_h) // 2
    for i, m in enumerate(masters):
        r, c = divmod(i, cols)
        flag = m.resize((fw, fh), Image.LANCZOS).convert('RGB')
        img.paste(flag, (x0 + c * (fw + gap), y0 + r * (fh + gap)))
    img.save(os.path.join(MOD, 'thumbnail.png'))


