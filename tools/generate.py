# Names that read naturally without "the" in front of them.
NO_ARTICLE = {
    'Yugoslavia', 'Francia', 'Gran Colombia', 'Maphilindo', 'Tawantinsuyu', 'Turan',
    'Greater Iran', 'Greater Ethiopia', 'Greater Mongolia',
}


# Letters that NFKD does not decompose into an ASCII base letter.
TRANSLITERATE = str.maketrans({'Ø': 'O', 'ø': 'o', 'Æ': 'AE', 'æ': 'ae', 'ß': 'ss', 'Ł': 'L', 'ł': 'l',
                               'Đ': 'D', 'đ': 'd', 'ı': 'i', 'Þ': 'Th', 'þ': 'th', 'Ð': 'D', 'ð': 'd'})


def ascii_comment(text):
    text = text.translate(TRANSLITERATE)
    return unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode()


def definite(name):
    return name if name in NO_ARTICLE else 'the ' + name


def write(rel, text, bom=False):
    path = os.path.join(MOD, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='\n') as f:
        f.write(text)


def continents(f):
    c = f['continent']
    return [c] if isinstance(c, str) else c


def or_block(lines, indent):
    pad = '\t' * indent
    if len(lines) == 1:
        return f'{pad}{lines[0]}\n'
    body = ''.join(f'{pad}\t{line}\n' for line in lines)
    return f'{pad}OR = {{\n{body}{pad}}}\n'


